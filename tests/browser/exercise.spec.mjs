import {test,expect}from'@playwright/test'
test.beforeEach(async({request})=>{const response=await request.post('/__academic_test',{data:{reset:true}});expect((await response.json()).data.reset).toBe(true)})
test('teacher creates, previews and publishes; student saves response; teacher releases feedback',async({page,browser})=>{
  const errors=[];page.on('pageerror',error=>errors.push(error.message))
  await page.goto('/tests/browser/fixture.html')
  await expect(page.locator('[data-studio-step="1"]')).toBeVisible()
  await page.getByRole('button',{name:'Create activity',exact:true}).click()
  await page.getByLabel('Title',{exact:true}).fill('Bonjour in a first meeting')
  await page.getByRole('combobox',{name:'Language',exact:true}).selectOption('French')
  await page.getByLabel('Prompt',{exact:true}).fill('Choose a greeting for your colleague.')
  await page.getByLabel('Options (one per line)',{exact:true}).fill('Bonjour\nAu revoir')
  await page.getByLabel('Correct option (private)',{exact:true}).fill('Bonjour')
  await page.getByRole('button',{name:'Save draft',exact:true}).click()
  await expect(page.locator('[data-form-status]')).toHaveText('Draft saved.')
  await page.getByRole('button',{name:'Preview activity',exact:true}).click()
  await expect(page.locator('[data-preview-host] input[type=radio]')).toHaveCount(2)
  await page.getByRole('button',{name:'Select students',exact:true}).click()
  await page.getByLabel('Find students',{exact:true}).fill('safe')
  await page.getByRole('checkbox',{name:/^Safe Test Student/}).check()
  await page.getByRole('button',{name:'Review publication',exact:true}).click()
  await page.getByRole('button',{name:'Publish and assign',exact:true}).click()
  await expect(page.locator('[data-form-status]')).toContainText('1 saved assignment')
  // Published content reopens locked; this prevents publishing a stale edited preview.
  await page.locator('[data-open-exercise]').click()
  await expect(page.getByLabel('Title',{exact:true})).toBeDisabled()
  const student=await browser.newPage()
  await student.goto('/tests/browser/fixture.html?actor=student')
  await expect(student.getByRole('heading',{name:'Bonjour in a first meeting'})).toBeVisible()
  await student.getByLabel('Bonjour',{exact:true}).check()
  await student.getByRole('button',{name:'Submit attempt',exact:true}).click()
  await expect(student.locator('[data-exercise-status]')).toHaveText('Attempt submitted for teacher review.')
  await student.reload()
  await expect(student.getByRole('button',{name:'Submitted for review',exact:true})).toBeDisabled()
  await page.reload()
  await expect(page.locator('[data-review-attempt]')).toHaveCount(1)
  await expect(page.locator('[data-review-attempt] ol')).toContainText('Bonjour')
  await page.getByLabel('Teacher feedback',{exact:true}).fill('Good greeting. Personalize it with your name next.')
  await page.getByRole('button',{name:'Save feedback draft',exact:true}).click()
  await expect(page.locator('[data-review-status]')).toHaveText('Feedback draft saved.')
  await student.reload();await expect(student.locator('.exercise-feedback')).toHaveCount(0)
  await page.getByRole('button',{name:'Approve and send feedback',exact:true}).click()
  await expect(page.locator('[data-review-status]')).toHaveText('Feedback published to student.')
  await student.reload();await expect(student.locator('.exercise-feedback')).toContainText('Personalize it with your name')
  expect(errors).toEqual([])
  await student.close()
})
test('matching activities retain deadlines and require a complete saved response',async({page,browser})=>{
  await page.goto('/tests/browser/fixture.html')
  await page.getByRole('combobox',{name:'Activity type',exact:true}).selectOption('matching')
  await page.getByRole('button',{name:'Create activity',exact:true}).click()
  await page.getByLabel('Title',{exact:true}).fill('Connect practical expressions')
  await page.getByLabel('Prompt',{exact:true}).fill('Match each expression to its meaning.')
  await page.getByLabel('Left expressions (one per line)',{exact:true}).fill('Bonjour\nMerci')
  await page.getByLabel('Right choices, in the order students will see (one per line)',{exact:true}).fill('Thank you\nHello')
  await page.getByRole('button',{name:'Preview activity',exact:true}).click()
  await expect(page.locator('[data-preview-host] select')).toHaveCount(2)
  await page.getByRole('button',{name:'Select students',exact:true}).click()
  await page.getByRole('checkbox',{name:/^Safe Test Student/}).check()
  await page.getByLabel('Deadline (your local time)',{exact:true}).fill('2035-02-01T09:15')
  await page.getByRole('button',{name:'Review publication',exact:true}).click()
  await page.getByRole('button',{name:'Publish and assign',exact:true}).click()
  await expect(page.locator('[data-form-status]')).toContainText('1 saved assignment')
  await page.getByRole('button',{name:/Connect practical expressions.*published/}).click()
  await page.getByRole('button',{name:'Preview activity',exact:true}).click()
  await page.getByRole('button',{name:'Select students',exact:true}).click()
  await expect(page.getByLabel('Deadline (your local time)',{exact:true})).toHaveValue('2035-02-01T09:15')
  const student=await browser.newPage()
  await student.goto('/tests/browser/fixture.html?actor=student')
  const card=student.locator('.exercise-activity').filter({has:student.getByRole('heading',{name:'Connect practical expressions',exact:true})})
  await card.locator('select').nth(0).selectOption('Hello')
  await card.getByRole('button',{name:'Submit attempt',exact:true}).click()
  await expect(card.locator('[data-exercise-status]')).not.toContainText('submitted')
  // Partial matching cannot save an attempt; the ready message is now visible.
  expect(await page.evaluate(async()=> (await window.testClient.from('exercise_attempts').select('*')).data.length)).toBe(0)
  await card.locator('select').nth(1).selectOption('Thank you')
  await card.getByRole('button',{name:'Submit attempt',exact:true}).click()
  await expect(card.locator('[data-exercise-status]')).toHaveText('Attempt submitted for teacher review.')
  await page.reload()
  const review=page.locator('[data-review-attempt]').filter({has:page.getByRole('heading',{name:/Connect practical expressions/})})
  await expect(review).toContainText('["Hello","Thank you"]')
  await student.close()
})
