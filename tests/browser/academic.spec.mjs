import { test, expect } from '@playwright/test'

test.beforeEach(async ({ request }) => {
  const response = await request.post('/__academic_test', { data: { reset: true } })
  expect((await response.json()).data.reset).toBe(true)
})

async function open(page, mode) {
  await page.goto(`/tests/browser/fixture.html?mode=${mode}`)
  await page.waitForFunction(() => window.testReady === true)
}

test('teacher saves and approves plan versions; student revisits history and records objective completion', async ({ page, browser }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await open(page, 'teacher-plans')
  await page.getByLabel('Find student', { exact: true }).fill('safe')
  await page.locator('[data-plan-student]').selectOption('20000000-0000-4000-8000-000000000001')
  await page.getByRole('button', { name: 'Create a plan draft', exact: true }).click()
  const editor = page.locator('[data-plan-edit]')
  await editor.getByLabel('Title', { exact: true }).fill('Practical first meetings')
  await editor.getByLabel('Language', { exact: true }).fill('French')
  await editor.getByLabel('Level', { exact: true }).fill('A1')
  await editor.getByLabel('Plan summary').fill('Use a greeting and introduce yourself in a real first meeting.')
  await editor.getByLabel('Communicative objective').fill('Introduce yourself to a colleague')
  await editor.getByLabel('How we will know it is complete').fill('A greeting, name and one personal detail in a short exchange.')
  for (const stage of ['Listen', 'Repeat', 'Personalize', 'Use']) {
    await editor.getByLabel(stage, { exact: true }).fill(`${stage} a brief introduction with your own name.`)
  }
  await editor.getByRole('button', { name: 'Save draft', exact: true }).click()
  await expect(page.locator('[data-plan-status]')).toHaveText('Learning plan draft saved.')
  const student = await browser.newPage()
  await open(student, 'student-plans')
  await expect(student.getByRole('heading', { name: /Practical first meetings/ })).toHaveCount(0)
  await page.getByRole('button', { name: 'Save and approve plan', exact: true }).click()
  await expect(page.locator('[data-plan-status]')).toContainText('approved and available')
  await student.reload()
  await expect(student.getByRole('heading', { name: /Practical first meetings/ })).toBeVisible()
  await student.getByLabel('Mark this objective complete', { exact: true }).check()
  await expect(student.locator('[data-plan-status]')).toHaveText('Objective completion saved.')
  await page.getByRole('button', { name: 'Create a new draft from this version' }).click()
  await page.locator('[data-plan-edit]').getByLabel('Title', { exact: true }).fill('Next steps in first meetings')
  await page.getByRole('button', { name: 'Save and approve plan', exact: true }).click()
  await expect(page.locator('[data-plan-status]')).toContainText('approved and available')
  await student.reload()
  await expect(student.locator('[data-plan-versions] button')).toHaveCount(2)
  await student.getByRole('button', { name: /Version 1 .*Practical first meetings/ }).click()
  await expect(student.getByLabel('Mark this objective complete')).toBeChecked()
  await student.getByRole('button', { name: 'View recent completion history' }).click()
  await expect(student.locator('[data-plan-events]')).toContainText('completed')
  await student.setViewportSize({ width: 390, height: 844 })
  expect(await student.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(errors).toEqual([])
  await student.close()
})

test('final assessment preview, assignment, response and private grade require explicit results publication', async ({ page, browser }) => {
  await open(page, 'teacher-finals')
  const inserted = await page.evaluate(async () => window.testClient.from('exercises').insert({
    teacher_id: '10000000-0000-4000-8000-000000000001', title: 'Conversation template', language: 'French',
    exercise_type: 'writing', instructions: 'Introduce yourself at a first meeting.', status: 'draft',
    questions: [{ prompt: 'Write your greeting and introduction.' }], settings: { max_attempts: 1 }
  }).select('id').single())
  expect(inserted.error).toBeFalsy()
  await page.reload()
  await page.getByRole('combobox', { name: 'Activity template', exact: true }).selectOption(inserted.data.id)
  await page.getByLabel('Final title', { exact: true }).fill('Final: A first meeting')
  await page.getByRole('combobox', { name: 'Student files', exact: true }).selectOption('none')
  await page.getByRole('button', { name: 'Save final draft', exact: true }).click()
  await expect(page.locator('[data-final-status]')).toContainText('Final draft saved')
  await page.getByRole('button', { name: 'Preview final', exact: true }).click()
  await expect(page.locator('[data-final-preview] .student-exercise-form')).toBeVisible()
  await expect(page.locator('[data-final-editor] .student-exercise-form')).toHaveCount(0)
  await page.getByLabel('Safe Test Student', { exact: true }).check()
  await page.getByRole('button', { name: 'Publish and assign final', exact: true }).click()
  await expect(page.locator('[data-final-status]')).toContainText('1 confirmed assignment')
  const student = await browser.newPage()
  await open(student, 'student-finals')
  await expect(student.getByRole('heading', { name: 'Final: A first meeting', exact: true })).toBeVisible()
  await student.getByRole('textbox', { name: 'Your answer to question 1' }).fill('Bonjour, je suis Camille. Je travaille ici.')
  await student.getByRole('button', { name: 'Submit attempt', exact: true }).click()
  await expect(student.locator('[data-exercise-status]')).toHaveText('Attempt submitted for teacher review.')
  await page.reload()
  const review = page.locator('[data-final-review]')
  await expect(review).toContainText('je suis Camille')
  await review.locator('[name="score-0"]').fill('35')
  await review.locator('[name="score-1"]').fill('25')
  await review.locator('[name="score-2"]').fill('25')
  await review.getByLabel('Private assessment feedback').fill('Clear introduction. Add one question for your colleague.')
  await review.getByRole('button', { name: 'Save private assessment' }).click()
  await expect(review.locator('[data-final-review-status]')).toContainText('85 / 100')
  await student.reload()
  await expect(student.getByRole('heading', { name: /Published result/ })).toHaveCount(0)
  await expect(student.getByText('Add one question for your colleague.', { exact: false })).toHaveCount(0)
  await review.getByRole('button', { name: 'Publish saved results to student' }).click()
  await expect(review.locator('[data-final-review-status]')).toContainText('published: 85 / 100')
  await student.reload()
  await expect(student.getByRole('heading', { name: /^Published result: 85(?:\.00)? \/ 100$/ })).toBeVisible()
  await expect(student.locator('.exercise-feedback')).toContainText('Add one question')
  await open(page, 'teacher')
  await expect(page.locator('[data-open-exercise]')).toHaveCount(1)
  await expect(page.locator('[data-open-exercise]')).toContainText('Conversation template')
  await student.close()
})

test('reviewed challenge recommendation publishes once; private feedback and unread notifications follow explicit release', async ({ page, browser, request }) => {
  // A labeled fixture recommendation exercises review/publication without a live
  // provider. Production generation stays disabled; this is never an AI result.
  const seed = await request.post('/__academic_test', { data: { seedChallenge: true } })
  expect((await seed.json()).data.id).toBeTruthy()
  await open(page, 'teacher-challenges')
  await expect(page.getByRole('button', { name: 'Generate editable recommendation' })).toBeDisabled()
  await page.getByRole('button', { name: 'Approve reviewed recommendation', exact: true }).click()
  const draft = page.locator('[data-challenge-draft]')
  await draft.locator('summary').click()
  await draft.getByRole('button', { name: 'Publish to selected students', exact: true }).click()
  await expect(page.getByText(/confirmed.*assignment|published.*student/i)).toBeVisible()
  await page.reload()
  await page.locator('[data-challenge-draft] summary').click()
  await expect(page.getByRole('button', { name: 'Already published', exact: true })).toBeDisabled()
  const student = await browser.newPage()
  await open(student, 'student-challenges')
  await expect(student.locator('.challenge-card')).toHaveCount(1)
  await student.locator('.challenge-submit-form textarea').fill('I used a greeting and introduced myself to a colleague.')
  await student.getByRole('button', { name: /Submit Challenge/ }).click()
  await expect(student.locator('.challenge-success-state')).toBeVisible()
  await page.reload()
  const review = page.locator('[data-review-challenge-response]')
  await review.getByLabel('Editable teacher feedback').fill('You made the greeting personal. Ask a follow-up question.')
  await review.getByRole('button', { name: 'Save private feedback draft', exact: true }).click()
  await expect(review.locator('[data-response-status]')).toHaveText('Private feedback draft saved.')
  await student.reload()
  await expect(student.locator('.teacher-feedback-note')).toHaveCount(0)
  await review.getByRole('button', { name: 'Approve and send feedback', exact: true }).click()
  await expect(review.locator('[data-response-status]')).toHaveText('Feedback published to the student.')
  await student.reload()
  await expect(student.locator('.teacher-feedback-note')).toContainText('Ask a follow-up question')
  await open(student, 'notifications')
  await expect(student.locator('.academic-notifications li.is-unread')).toHaveCount(2)
  await student.getByRole('button', { name: 'Mark as read', exact: true }).first().click()
  await expect(student.locator('.academic-notifications li.is-read')).toHaveCount(1)
  await student.reload()
  await expect(student.locator('.academic-notifications li.is-read')).toHaveCount(1)
  await student.close()
})
