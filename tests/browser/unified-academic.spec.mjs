async function reviewAndIndex(page) {
  const form = page.locator('[data-academic-review]')
  await expect(form).toBeVisible()
  await form.locator('[name=confirmed]').check()
  await form.getByRole('button', { name: 'Save reviewed context', exact: true }).click()
  await expect(page.locator('[data-context-status]')).toContainText('Reviewed context saved')
  await form.locator('[data-review-ai-context] > summary').click()
  await form.getByRole('button', { name: 'Extract document text', exact: true }).click()
  await expect(page.locator('[data-context-status]')).toContainText('Document status: ready')
  await page.locator('[data-academic-review]').getByRole('button', { name: 'Save reviewed context', exact: true }).click()
  await expect(page.locator('[data-context-status]')).toContainText('Reviewed context saved')
}
